// Helper functions for easy querying
export function getDistricts(divisionBn: string): District[] {
  const div = bangladeshDivisions.find(d => d.nameBn === divisionBn);
  return div ? div.districts : [];
}

export function getUpazilas(divisionBn: string, districtBn: string): UpazilaInfo[] {
  const districts = getDistricts(divisionBn);
  const dist = districts.find(d => d.nameBn === districtBn);
  return dist ? dist.upazilas : [];
}

export function getUnions(divisionBn: string, districtBn: string, upazilaBn: string): string[] {
  const upazilas = getUpazilas(divisionBn, districtBn);
  const up = upazilas.find(u => u.nameBn === upazilaBn);
  if (up && up.unions && up.unions.length > 0) {
    return up.unions;
  }
  // Default fallback unions if not specifically listed
  return [
    `${upazilaBn} পৌরসভা / সদর ওয়ার্ড`,
    "১নং ওয়ার্ড / ইউনিয়ন",
    "২নং ওয়ার্ড / ইউনিয়ন",
    "৩নং ওয়ার্ড / ইউনিয়ন",
    "৪নং ওয়ার্ড / ইউনিয়ন",
    "৫নং ওয়ার্ড / ইউনিয়ন",
    "অন্যান্য / নতুন ইউনিয়ন"
  ];
}
