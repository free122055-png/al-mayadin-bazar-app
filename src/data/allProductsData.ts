/**
 * Seed initial demo products to Firestore if products collection is empty
 * or force seed with merge.
 */
export async function seedDemoProducts(force = false): Promise<number> {
  try {
    const productsRef = collection(db, "products");
    const existingSnap = await getDocs(productsRef);

    if (!force && existingSnap.size >= ALL_INITIAL_PRODUCTS.length) {
      console.log(`Firestore already has ${existingSnap.size} products. Skipping auto-seed.`);
      return existingSnap.size;
    }

    // Write all initial products in chunks of 100
    let count = 0;
    const chunkSize = 100;
    for (let i = 0; i < ALL_INITIAL_PRODUCTS.length; i += chunkSize) {
      const chunk = ALL_INITIAL_PRODUCTS.slice(i, i + chunkSize);
      const batch = writeBatch(db);
      for (const prod of chunk) {
        const docRef = doc(db, "products", prod.id);
        batch.set(docRef, prod, { merge: true });
        count++;
      }
      await batch.commit();
    }

    console.log(`Successfully seeded/synced ${count} products to Firestore!`);
    return count;
  } catch (error) {
    console.error("Error seeding initial products to Firestore:", error);
    // Fallback: Individual setDoc
    try {
      let singleCount = 0;
      for (const prod of ALL_INITIAL_PRODUCTS) {
        await setDoc(doc(db, "products", prod.id), prod, { merge: true });
        singleCount++;
      }
      return singleCount;
    } catch (fallbackError) {
      console.error("Fallback seed error:", fallbackError);
      return 0;
    }
  }
}
